"""Acceptance probe for Ollama's native speech endpoint, independent of adapters."""

from __future__ import annotations

import io
import time
import wave
from pathlib import Path
from typing import Any

import httpx

from training_suite.core.config import DEFAULT_OLLAMA_URL


def ollama_speech_smoke(
    model: str,
    *,
    ollama_url: str = DEFAULT_OLLAMA_URL,
    text: str = "This speech is generated by Ollama from the selected model weights.",
    voice: str = "default",
    response_format: str = "wav",
    timeout: float = 180,
    audio_out: Path | None = None,
    client: httpx.Client | None = None,
) -> dict[str, Any]:
    """Require native speech capability and validate the actual returned samples.

    A structural probe does not establish transcription accuracy or cloned
    speaker similarity. No reference-audio field exists in the stock API.
    """
    started = time.monotonic()
    report: dict[str, Any] = {
        "ok": False,
        "model": model,
        "endpoint": ollama_url.rstrip("/") + "/v1/audio/speech",
        "execution_owner": "ollama",
        "spoken_content_verified": False,
        "voice_similarity_verified": False,
    }
    session = client or httpx.Client(timeout=timeout)
    try:
        if response_format not in {"wav", "pcm"}:
            raise ValueError("response_format must be wav or pcm")
        if not isinstance(text, str) or not text.strip() or len(text) > 4096:
            raise ValueError("text must contain 1–4096 characters")
        shown = session.post(
            ollama_url.rstrip("/") + "/api/show", json={"model": model}
        )
        shown.raise_for_status()
        metadata = shown.json()
        if not isinstance(metadata, dict):
            raise ValueError("/api/show returned a non-object response")
        report["capabilities"] = metadata.get("capabilities", [])
        report["voices"] = metadata.get("voices", [])
        if "speech" not in report["capabilities"]:
            raise ValueError(
                "selected tag does not advertise native speech; adapter audio-output "
                "and attached Qwen TTS weights do not satisfy this gate"
            )
        response = session.post(
            report["endpoint"],
            json={
                "model": model,
                "input": text,
                "voice": voice,
                "response_format": response_format,
            },
        )
        report["status_code"] = response.status_code
        if response.is_error:
            raise ValueError(
                f"native speech returned HTTP {response.status_code}: {response.text[:500]}"
            )
        content_type = response.headers.get("content-type", "").split(";", 1)[0].lower()
        if response_format == "wav":
            if content_type not in {"audio/wav", "audio/wave", "audio/x-wav"}:
                raise ValueError(
                    "native speech must return binary WAV, not a JSON audio envelope"
                )
            with wave.open(io.BytesIO(response.content), "rb") as wav:
                if (
                    wav.getframerate(),
                    wav.getnchannels(),
                    wav.getsampwidth(),
                    wav.getcomptype(),
                ) != (24000, 1, 2, "NONE"):
                    raise ValueError("native speech WAV must be 24 kHz mono PCM16")
                # Streamed WAV headers declare an unknown (maximum) length.
                # Count samples actually received instead of trusting getnframes().
                pcm = wav.readframes(wav.getnframes())
        else:
            if content_type not in {"audio/pcm", "application/octet-stream"}:
                raise ValueError("native speech must return binary PCM")
            pcm = response.content
        if not pcm or len(pcm) % 2:
            raise ValueError("native speech returned empty or incomplete PCM16 samples")
        if not any(pcm):
            raise ValueError("native speech returned only digital silence")
        report["output"] = {
            "container": response_format,
            "sample_rate_hz": 24000,
            "channels": 1,
            "sample_width_bits": 16,
            "frames": len(pcm) // 2,
            "duration_ms": round(len(pcm) * 1000 / 48000),
            "received_bytes": len(response.content),
        }
        if audio_out is not None:
            audio_out.parent.mkdir(parents=True, exist_ok=True)
            audio_out.write_bytes(response.content)
            report["audio_path"] = str(audio_out)
        report["ok"] = True
    except (
        httpx.HTTPError,
        ValueError,
        TypeError,
        wave.Error,
        EOFError,
        OSError,
    ) as exc:
        report["error"] = str(exc)
    finally:
        if client is None:
            session.close()
        report["elapsed_s"] = round(time.monotonic() - started, 2)
    return report
